-- Cradlewell database on Supabase (PostgreSQL). `npm run db:setup` runs this file once in the
-- schema "app" (the app's data) and once in "app_test" (the tests), so the two never mix.
-- These schemas are not exposed through Supabase's public API; RLS is also switched on with no
-- policies, so the anon and authenticated keys can never read or change a row. Only the server
-- (connecting with the database password, as the tables' owner) uses them.
-- Safe to run again. All times are timestamptz (stored in UTC).

-- Like MySQL's ON UPDATE CURRENT_TIMESTAMP: refresh updated_at unless the update set it itself.
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END $$;

-- ---- Accounts, codes and sessions --------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name           varchar(120) NOT NULL,
  phone               varchar(20)  NOT NULL,  -- E.164, e.g. +919876543210 (admins: a placeholder)
  email               varchar(254) NOT NULL,  -- lower-cased
  password_hash       varchar(100) NOT NULL,  -- bcrypt
  verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending', 'verified')),
  -- nurse: opens families by phone; client: a parent who sees only their own family; admin: dashboard only
  role                text NOT NULL DEFAULT 'nurse' CHECK (role IN ('nurse', 'client', 'admin')),
  google_sub          varchar(64),            -- Google account id, set after signing in with Google
  -- nurses who sign up in the app wait for the admin to approve them
  approval_status     text NOT NULL DEFAULT 'approved' CHECK (approval_status IN ('pending', 'approved', 'rejected')),
  verified_at         timestamptz,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT uq_users_phone UNIQUE (phone)
);

-- One-time codes, stored only as an HMAC. user_id becomes NULL when the account is deleted, so
-- the code still counts toward the daily limit for that phone or email.
CREATE TABLE IF NOT EXISTS otp_codes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purpose     text NOT NULL CHECK (purpose IN ('registration', 'client_access', 'password_reset')),
  user_id     bigint REFERENCES users (id) ON DELETE SET NULL,
  client_id   bigint,                      -- clients.id for client_access codes
  phone       varchar(255) NOT NULL,       -- phone number or email address the code was sent to
  code_hash   char(64) NOT NULL,           -- HMAC-SHA256(OTP_SECRET, code)
  attempts    smallint NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  expires_at  timestamptz NOT NULL,
  consumed_at timestamptz,                 -- set when used or superseded: a code works only once
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_otp_lookup ON otp_codes (user_id, purpose, phone, consumed_at);
CREATE INDEX IF NOT EXISTS idx_otp_dest ON otp_codes (phone, purpose, created_at);

CREATE TABLE IF NOT EXISTS sessions (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash         char(64) NOT NULL,    -- SHA-256 of the bearer token
  client_id          bigint,               -- the family opened in this session
  client_verified_at timestamptz,
  expires_at         timestamptz NOT NULL,
  revoked_at         timestamptz,          -- set on logout
  last_used_at       timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_sessions_token UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);

-- App errors sent by phones: what failed and where, never user or baby data. Kept 90 days.
CREATE TABLE IF NOT EXISTS crash_reports (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message     varchar(500) NOT NULL,
  stack       text,
  is_fatal    boolean NOT NULL DEFAULT false,
  app_version varchar(20),
  platform    varchar(40),
  screen      varchar(60),
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_crash_created ON crash_reports (created_at);

-- ---- Families, babies and records ----------------------------------------------------------

-- A family (client). Shared by all nurses: opened by phone number plus the parent's code.
CREATE TABLE IF NOT EXISTS clients (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          varchar(120) NOT NULL,
  phone         varchar(20)  NOT NULL,     -- E.164
  user_id       bigint REFERENCES users (id) ON DELETE SET NULL,  -- the parent's own account
  email         varchar(255),              -- parent's email for access codes; the parent account's email wins
  email_trusted boolean NOT NULL DEFAULT false,  -- entered by the admin, so Google sign-in with it may claim the family
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_clients_phone UNIQUE (phone)
);
CREATE INDEX IF NOT EXISTS idx_clients_user ON clients (user_id);

-- Which nurse may open which family without a new code (made when the family's code is entered).
-- opened_at: the last time the nurse entered the family's number (it reopens by itself for 30 days).
CREATE TABLE IF NOT EXISTS client_access (
  user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,   -- the nurse
  client_id  bigint NOT NULL REFERENCES clients (id) ON DELETE CASCADE,
  granted_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz,                  -- NULL: never expires
  revoked_at timestamptz,
  opened_at  timestamptz,
  PRIMARY KEY (user_id, client_id)
);
CREATE INDEX IF NOT EXISTS idx_access_client ON client_access (client_id);

-- Nurse visits for the admin dashboard: one row per nurse, family and day (India time).
CREATE TABLE IF NOT EXISTS client_visits (
  user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,   -- the nurse
  client_id  bigint NOT NULL REFERENCES clients (id) ON DELETE CASCADE,
  visit_date date NOT NULL,                -- day in India time (UTC+5:30)
  first_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, client_id, visit_date)
);
CREATE INDEX IF NOT EXISTS idx_visits_date ON client_visits (visit_date);
CREATE INDEX IF NOT EXISTS idx_visits_client ON client_visits (client_id);

CREATE TABLE IF NOT EXISTS babies (
  id         varchar(64) PRIMARY KEY,      -- generated by the app
  client_id  bigint NOT NULL REFERENCES clients (id) ON DELETE CASCADE,
  name       varchar(120) NOT NULL,
  details    jsonb NOT NULL,               -- full profile: dob, gender, birth weight, feeding type...
  position   integer NOT NULL DEFAULT 0,   -- display order, higher first
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_babies_client ON babies (client_id);

-- Every monitoring entry, stored exactly as the app saves it.
CREATE TABLE IF NOT EXISTS monitoring_records (
  baby_id     varchar(64) NOT NULL REFERENCES babies (id) ON DELETE CASCADE,
  record_type text NOT NULL CHECK (record_type IN ('feeding', 'sleep', 'diaper', 'medicine', 'growth',
                'vaccination', 'temperature', 'breathing', 'skin', 'milestone')),
  id          varchar(64) NOT NULL,        -- generated by the app
  data        jsonb NOT NULL,
  position    integer NOT NULL DEFAULT 0,  -- display order, higher first
  updated_by  bigint REFERENCES users (id) ON DELETE SET NULL,  -- last user to write it
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (baby_id, record_type, id)
);
CREATE INDEX IF NOT EXISTS idx_records_writer ON monitoring_records (updated_by, updated_at);
CREATE INDEX IF NOT EXISTS idx_records_created ON monitoring_records (created_at);

-- ---- updated_at triggers -------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_users_updated BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE OR REPLACE TRIGGER trg_otp_updated BEFORE UPDATE ON otp_codes FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE OR REPLACE TRIGGER trg_sessions_updated BEFORE UPDATE ON sessions FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE OR REPLACE TRIGGER trg_clients_updated BEFORE UPDATE ON clients FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE OR REPLACE TRIGGER trg_babies_updated BEFORE UPDATE ON babies FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE OR REPLACE TRIGGER trg_records_updated BEFORE UPDATE ON monitoring_records FOR EACH ROW EXECUTE FUNCTION touch_updated_at();

-- ---- Row-Level Security --------------------------------------------------------------------
-- On for every table with no policies: Supabase's anon and authenticated roles get nothing.
-- The server connects as the tables' owner, which RLS does not restrict.

ALTER TABLE users              ENABLE ROW LEVEL SECURITY;
ALTER TABLE otp_codes          ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions           ENABLE ROW LEVEL SECURITY;
ALTER TABLE crash_reports      ENABLE ROW LEVEL SECURITY;
ALTER TABLE clients            ENABLE ROW LEVEL SECURITY;
ALTER TABLE client_access      ENABLE ROW LEVEL SECURITY;
ALTER TABLE client_visits      ENABLE ROW LEVEL SECURITY;
ALTER TABLE babies             ENABLE ROW LEVEL SECURITY;
ALTER TABLE monitoring_records ENABLE ROW LEVEL SECURITY;
